-- Preview: backup rows matched to the database and differing statuses.
SELECT r.sheet_name,
       count(*) AS backup_records,
       count(s.id) AS matched_database_rows,
       count(s.id) FILTER (WHERE s.data->>'Status' IS DISTINCT FROM r.backup_status) AS statuses_to_change,
       count(*) FILTER (WHERE s.id IS NULL) AS backup_rows_missing_from_database
FROM backup_status_restore r
LEFT JOIN sheet_rows s ON s.id = r.row_id AND s.sheet_name = r.sheet_name
GROUP BY r.sheet_name
ORDER BY r.sheet_name;

-- Apply the status-only update and show the number changed per dataset.
WITH updated AS (
    UPDATE sheet_rows s
    SET data = jsonb_set(s.data, '{Status}', to_jsonb(r.backup_status), true)
    FROM backup_status_restore r
    WHERE s.id = r.row_id
      AND s.sheet_name = r.sheet_name
      AND s.data->>'Status' IS DISTINCT FROM r.backup_status
    RETURNING s.sheet_name
)
SELECT sheet_name, count(*) AS statuses_updated
FROM updated
GROUP BY sheet_name
ORDER BY sheet_name;

